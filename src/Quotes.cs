    static readonly Random rnd = new Random();
    static List<int> bag = new List<int>();
    static int last = -1;

    public static int Count { get { return All.Length; } }

    public static string[] Next()
    {
        if (bag.Count == 0)
        {
            for (int i = 0; i < All.Length; i++) bag.Add(i);
            for (int i = bag.Count - 1; i > 0; i--)
            {
                int j = rnd.Next(i + 1);
                int t = bag[i]; bag[i] = bag[j]; bag[j] = t;
            }
            // 새 한 바퀴의 첫 문장이 직전 문장과 같지 않도록
            if (bag[bag.Count - 1] == last && bag.Count > 1)
            {
                int t = bag[bag.Count - 1]; bag[bag.Count - 1] = bag[0]; bag[0] = t;
            }
        }
        last = bag[bag.Count - 1];
        bag.RemoveAt(bag.Count - 1);
        return All[last];
    }
